from engine.messages import Message


def translate(text: str, language: str) -> str:
    if language != "zh-TW":
        return str(text)
    if isinstance(text, Message):
        template = ZH_TW.get(text.template, text.template)
        fields = {key: translate(value, language) if isinstance(value, str) else value
                  for key, value in text.values.items()}
        return template.format(**fields)
    return ZH_TW.get(text, text)


